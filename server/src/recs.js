/** Блоки рекомендаций для отчёта: [{ title, items[] }] */
export function buildRecommendations({ procedure, pests = [], infestation, preparation, premises = [], reentry = '' }) {
  const blocks = [];
  const notes = [];
  if (preparation === 'none' || preparation === 'partial') {
    notes.push(preparation === 'none'
      ? 'Помещение не было подготовлено к обработке — эффективность может быть снижена. Необходимо выполнить подготовку и провести повторную обработку.'
      : 'Подготовка помещения выполнена частично — в недоступных местах эффективность может быть снижена. Рекомендуется устранить замечания до повторной обработки.');
  }
  if (infestation === 'high' || infestation === 'critical') {
    notes.push(infestation === 'critical'
      ? 'Критическая заселённость: требуется курс из 2–3 обработок и контрольный осмотр. Рекомендуется проверить смежные помещения.'
      : 'Высокая заселённость: обязательна повторная обработка и контрольный осмотр.');
  }
  if (notes.length) blocks.push({ title: 'Важно', items: notes, accent: true });
  const re = reentryBlock(reentry, 'ru');
  if (re) blocks.push(re);
  blocks.push(...premiseBlocks(premises, 'ru'));
  const generalAfter = re ? GENERAL_AFTER.slice(1) : GENERAL_AFTER;

  if (procedure === 'Дезинфекция' && !pests.length) {
    blocks.push({ title: 'Подготовка к обработке', items: DISINFECTION.before });
    blocks.push({ title: 'После обработки', items: [...DISINFECTION.after, DISINFECTION.repeat] });
    return blocks;
  }

  const known = pests.filter((p) => PESTS[p]);
  for (const p of known) {
    const r = PESTS[p];
    blocks.push({ title: `${p}: подготовка`, items: r.before });
    blocks.push({ title: `${p}: после обработки`, items: [...r.after, r.repeat] });
  }
  if (procedure !== 'Дератизация') {
    blocks.push({ title: 'Общие правила', items: [...GENERAL_BEFORE, ...generalAfter] });
  }
  return blocks;
}
